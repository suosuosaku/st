function cleanBaguText(text) {
  let output = String(text);
  const replacements = [
    [/似乎/g, ''],
    [/几乎/g, ''],
    [/近乎/g, ''],
    [/好像/g, ''],
    [/仿佛/g, ''],
    [/如同/g, ''],
    [/宛如/g, ''],
    [/看似/g, '表面'],
    [/不冷不热/g, '公事公办'],
    [/口吻/g, '风格'],
    [/语气/g, '表达'],
    [/声音/g, '发言'],
    [/声线/g, '发言'],
    [/眼里/g, ''],
    [/眼中/g, ''],
    [/嘴角/g, ''],
    [/神色/g, '表情'],
    [/神态/g, '状态'],
    [/微笑/g, '笑'],
    [/下意识/g, '习惯性'],
    [/无意识/g, '习惯性'],
    [/极度/g, ''],
    [/极大/g, ''],
    [/非常/g, ''],
  ];
  for (const [pattern, replacement] of replacements) {
    output = output.replace(pattern, replacement);
  }
  output = output.replace(/是不是/g, '是否');
  output = output.replace(/不是[^，。；\n]*而是/g, '');
  output = output.replace(/不是/g, '');
  output = output.replace(/像小兔子一样|像小动物一样|像小兽一样|小兔子一样|小动物一样|小兽一样/g, '');
  output = output
    .split('\n')
    .filter(line => !/(瞳色|瞳孔|罩杯|三维|cm|厘米|不容置疑|每一个字都带着|投石|一丝|难以察觉|绝望|恐惧|畏缩|机械化|一卡一卡|僵硬|空白|脆弱)/.test(line))
    .join('\n');
  output = output.replace(/[ \t]+$/gm, '');
  output = output.replace(/\n{4,}/g, '\n\n\n');
  return output;
}

