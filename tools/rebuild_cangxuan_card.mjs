function makeEntry({ comment, keys = [], content, constant = false, selective = true, insertion_order = 300, position = 'before_char', use_regex = true, source = {} }) {
  return {
    id: 0,
    keys,
    secondary_keys: [],
    comment,
    content,
    constant,
    selective,
    insertion_order,
    enabled: true,
    position,
    use_regex,
    extensions: baseExtensions(0, source.extensions || {}),
  };
}

function pureToCardEntry(entry, override = {}) {
  return makeEntry({
    comment: entry.comment,
    keys: entry.key || [],
    content: entry.content,
    constant: Boolean(entry.constant),
    selective: entry.selective !== false,
    insertion_order: entry.order ?? 300,
    position: 'before_char',
    use_regex: true,
    source: entry,
    ...override,
  });
}

