function appendLandmarkDetails(entry) {
  const lines = distanceData[entry.comment];
  let extra = '';
  if (lines) {
    extra += `\n\n  地图与距离:\n${lines.map(line => `    ${line}`).join('\n')}`;
  }
  extra += `\n\n  建筑与事件触发:\n    建筑细节: 进入此地时优先描写入口、主路、标志性建筑、可交易/可互动场所与人群密度。\n    日常触发: 可触发问路、采购、路人闲谈、宗门差事、巡逻盘查、临时委托。\n    事件触发: 当{{user}}主动探索、接近禁地、打听消息或交易时，引入与本地势力匹配的NPC或突发事件。\n    地图使用: 叙事移动必须说明从哪个相邻地点进入、距离远近、通行方式与消耗时间。`;
  return entry.content.replace(/\n?<\/([^>]+)>\s*$/, `${extra}\n</$1>`);
}

