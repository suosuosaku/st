  const concreteLines = Array.isArray(palette[4]);
  const place = location.split('·').pop();
  const anchor = clothes[2] || clothes[1] || clothes[0];
  const actionLines = sourceActions.length ? sourceActions : relation;
  const trimEnd = value => String(value || '').replace(/[。；，,.]+$/g, '');
