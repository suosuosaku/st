function patchOpening(script) {
  if (!script || typeof script.replaceString !== 'string') return;
  let html = script.replaceString;
  if (!html.includes('name: "慕泽"')) {
    const extraCharacters = OPENING_EXTRA_CHARACTERS.map(character => (
      `            { id: ${character.id}, name: "${character.name}", sect: "${character.sect}", title: "${character.title}", front: "${PLACEHOLDER_IMAGE}", avatar: "${PLACEHOLDER_IMAGE}", desc: "${character.desc}" }`
    )).join(',\n');
    html = html.replace(
      /(\s*\{ id: 16, name: "潮听澜"[\s\S]*?desc: "[^"]+" \})(\s*\n\s*\];\s*\n\s*\/\/ ================= 数据库：苍玄大地图)/,
      `$1,\n${extraCharacters}$2`
    );
  }

  if (!html.includes('name: "赤铃沙海"')) {
    const desertLocation = '            { id: "desert", name: "赤铃沙海", tag: "南域偏西 · 百蛊绿洲", icon: "fa-bell", desc: "<p>位于南域偏西、万器山以南与十万大山以西的广阔沙海，沙风里常夹着银铃与蛊虫振翅声。</p><p>百蛊绿洲是沙海核心寨城，外来修士入寨需登记蛊契；鸣沙驿负责沙舟航线，赤沙禁域则是连老向导都要先摸护身符的高危区。</p><p><strong>风物：</strong>苗疆式银饰、彩布、蛊棚、水井账册和沙舟驼铃混在一起，热闹时像集市，严肃时像账房点名。</p>" },';
    html = html.replace(
      /(\s*\{ id: "wanqi", name: "万器山"[\s\S]*?desc: "[^"]+" \},\n)/,
      `$1${desertLocation}\n`
    );
  }
  script.replaceString = html;
}

